import type { Finding } from '../types.ts';
import { isDistro } from '../vulns/ecosystems.ts';

const DECISION_HELP: Record<Finding['decision'], string> = {
  Act: 'Fix now',
  Attend: 'Fix next cycle',
  'Track*': 'Watch',
  Track: 'Set aside with evidence',
};

const TIER_LABEL: Record<Finding['reach']['tier'], string> = {
  reachable: 'Reachable from an entry point',
  'called-unreached': 'Called, but no entry point reaches it',
  'imported-unknown-symbol': 'Imported; no function-level data yet',
  'image-only': 'In the container image; no code path traced',
  'imported-not-called': 'Imported, vulnerable function never called',
  unused: 'Installed but never imported',
  'dev-only': 'Dev dependency, not shipped',
};

export function bestPathOf(f: Finding) {
  return f.reach.paths.find((x) => !x.entry.authenticated && x.userInput) ?? f.reach.paths.find((x) => !x.entry.authenticated) ?? f.reach.paths.find((x) => x.userInput) ?? f.reach.paths[0];
}

export function fixCommandFor(f: Finding): string | undefined {
  const v = f.advisory.fixedVersion;
  if (!v) return undefined;
  const { ecosystem: eco, name } = f.component;
  if (eco === 'npm') return `npm install ${name}@${v}`;
  if (eco === 'PyPI') return `pip install "${name}==${v}"`;
  if (eco === 'Go') return `go get ${name}@${v.startsWith('v') ? v : 'v' + v}`;
  if (eco === 'RubyGems') return `gem install ${name} -v ${v}`;
  if (eco === 'crates.io') return `cargo update -p ${name} --precise ${v}`;
  if (eco === 'NuGet') return `dotnet add package ${name} --version ${v}`;
  if (eco === 'Packagist') return `composer require ${name}:${v}`;
  if (/^(Debian|Ubuntu)/.test(eco)) return `apt-get update && apt-get install --only-upgrade -y ${name}`;
  if (/^(Alpine|Wolfi|Chainguard)/.test(eco)) return `apk upgrade --no-cache ${name}`;
  if (isDistro(eco)) return `dnf upgrade -y ${name}`;
  return undefined;
}

export function ticketTitle(f: Finding): string {
  return `[${f.decision}] ${f.component.name}@${f.component.version}: ${f.advisory.cve ?? f.advisory.id} — ${f.advisory.summary}`;
}

/** The ticket body, in Markdown, that a tracker gets for one finding. */
export function ticketMarkdown(f: Finding, targetName: string): string {
  const lines = [
    `# ${ticketTitle(f)}`,
    '',
    `**Target:** ${targetName}  `,
    `**Decision:** ${f.decision} (${DECISION_HELP[f.decision]})  `,
    `**Score:** ${f.score}/100  `,
    `**Reachability:** ${TIER_LABEL[f.reach.tier]} (confidence: ${f.reach.confidence})  `,
    '',
    '## Why',
    ...f.why.map((w) => `- ${w}`),
    '',
  ];
  const p = bestPathOf(f);
  if (p) {
    lines.push('## Path', '```', `${p.entry.method} ${p.entry.path}${p.entry.authenticated ? ' [auth: ' + p.entry.guards.join(', ') + ']' : ' [no auth]'}`);
    for (const h of p.hops) lines.push(`  → ${h.name}  (${h.file}:${h.line})`);
    lines.push(`  → ${p.callSite.text}()  (${p.callSite.file}:${p.callSite.line})`, '```');
    if (p.userInput && p.taintedArgument) lines.push(`Request data \`${p.inputSource ?? ''}\` arrives as argument ${p.taintedArgument.index + 1} (\`${p.taintedArgument.text}\`).`);
    lines.push('');
  }
  lines.push('## Fix');
  const cmd = fixCommandFor(f);
  if (cmd) lines.push(`${f.fix}`, '', '```bash', cmd, '```', '');
  else lines.push('No fixed version is published yet. Mitigate at the entry point.', '');
  if (f.advisory.references.length) lines.push('## References', ...f.advisory.references.slice(0, 6).map((r) => `- ${r}`), '');
  lines.push('_Generated by NextFix._');
  return lines.join('\n');
}
