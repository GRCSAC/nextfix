import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readYarnLock, splitDescriptor } from './yarn-lock.ts';

const YARN_APP = fileURLToPath(new URL('../../test-fixtures/yarn-app/', import.meta.url));

test('descriptors split on the right @ for scoped and aliased packages', () => {
  assert.deepEqual(splitDescriptor('lodash@4.17.15'), { name: 'lodash', range: '4.17.15' });
  assert.deepEqual(splitDescriptor('@babel/code-frame@^7.10.0'), { name: '@babel/code-frame', range: '^7.10.0' });
  assert.deepEqual(splitDescriptor('string-width-cjs@npm:string-width@^4.2.0'), { name: 'string-width-cjs', range: 'npm:string-width@^4.2.0' });
  assert.deepEqual(splitDescriptor('app@workspace:.'), { name: 'app', range: 'workspace:.' });
});

test('yarn classic: scoped packages, an alias under its real name, dev and optional by walking', () => {
  const inv = readYarnLock(YARN_APP);
  assert.equal(inv.lockfileVersion, 1);
  assert.equal(inv.projectName, 'yarn-app');
  assert.equal(inv.projectVersion, '2.0.0');
  const by = new Map(inv.components.map((c) => [c.name, c]));
  assert.deepEqual([...by.keys()].sort(), ['@babel/code-frame', '@babel/highlight', 'ansi-styles', 'chalk', 'emoji-regex', 'fsevents', 'lodash', 'minimist', 'string-width']);

  const scoped = by.get('@babel/code-frame')!;
  assert.equal(scoped.purl, 'pkg:npm/%40babel/code-frame@7.10.4');
  assert.equal(scoped.direct, true);
  assert.equal(scoped.dev, false);
  assert.equal(scoped.path, 'yarn.lock:@babel/code-frame@^7.10.0');

  const aliased = by.get('string-width')!;
  assert.equal(aliased.version, '4.2.3');
  assert.equal(aliased.purl, 'pkg:npm/string-width@4.2.3', 'queried as the real package');
  assert.equal(aliased.direct, true, 'direct-ness follows the alias the manifest names');
  assert.equal(aliased.path, 'yarn.lock:string-width-cjs@npm:string-width@^4.2.0');
  assert.equal(by.get('emoji-regex')!.dev, false, 'reached through the alias from a prod dependency');

  assert.equal(by.get('chalk')!.direct, false);
  assert.equal(by.get('chalk')!.dev, false, 'transitive of a prod dependency');
  assert.equal(by.get('minimist')!.dev, true, 'only reachable from devDependencies');
  assert.equal(by.get('minimist')!.direct, true);
  assert.equal(by.get('fsevents')!.optional, true, 'only reachable through optionalDependencies');
  assert.equal(by.get('fsevents')!.dev, false);
  assert.equal(by.get('lodash')!.optional, false);
});

