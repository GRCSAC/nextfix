import { test } from 'node:test';
import assert from 'node:assert/strict';
import { IntegrationError, markdownToAdf, mergeIntegrationConfig } from './integrations.ts';

test('markdown ticket body converts to Atlassian Document Format', () => {
  const md = ['# [Act] lodash@4.17.15: CVE-2021-23337 — Command Injection', '', '**Target:** express-shop  ', '**Score:** 81/100  ', '', '## Why', '- lodash is affected', '- Reachable: POST /preview → `_.template()`', '', '## Fix', 'Upgrade lodash 4.17.15 → 4.17.21', '', '```bash', 'npm install lodash@4.17.21', '```', '', '_Generated by NextFix._'].join('\n');
  const doc = markdownToAdf(md) as { type: string; version: number; content: { type: string; attrs?: { level?: number }; content?: unknown[] }[] };
  assert.equal(doc.type, 'doc');
  assert.equal(doc.version, 1);
  const types = doc.content.map((c) => c.type);
  assert.deepEqual(types, ['heading', 'paragraph', 'heading', 'bulletList', 'heading', 'paragraph', 'codeBlock', 'paragraph']);
  assert.equal(doc.content[0]!.attrs!.level, 1);
  const para = doc.content[1]!.content as { type: string; text?: string; marks?: { type: string }[] }[];
  assert.equal(para[0]!.marks?.[0]?.type, 'strong');
  assert.ok(para.some((n) => n.type === 'hardBreak'), 'two-space line endings become hard breaks');
  const list = doc.content[3]!.content as { content: { content: { marks?: { type: string }[] }[] }[] }[];
  assert.equal(list.length, 2);
  assert.ok(list[1]!.content[0]!.content.some((n) => n.marks?.[0]?.type === 'code'));
  const code = doc.content[6]!.content as { text: string }[];
  assert.equal(code[0]!.text, 'npm install lodash@4.17.21');
});

test('http(s) URLs in the ticket body become clickable links', () => {
  const md = ['## References', '- https://github.com/advisories/GHSA-35jh-r3h4-6jhm', '- See https://nvd.nist.gov/vuln/detail/CVE-2021-23337.', '', 'Wrapped (https://example.com/a_(b)) and `https://not-a-link.test`'].join('\n');
  type Node = { type: string; text: string; marks?: { type: string; attrs?: { href: string } }[] };
  const doc = markdownToAdf(md) as { content: { type: string; content: { content: { content: Node[] }[] }[] }[] };
  const items = doc.content[1]!.content;
  const first = items[0]!.content[0]!.content[0]!;
  assert.equal(first.text, 'https://github.com/advisories/GHSA-35jh-r3h4-6jhm');
  assert.deepEqual(first.marks, [{ type: 'link', attrs: { href: 'https://github.com/advisories/GHSA-35jh-r3h4-6jhm' } }]);
  const second = items[1]!.content[0]!.content;
  assert.equal(second[1]!.marks![0]!.attrs!.href, 'https://nvd.nist.gov/vuln/detail/CVE-2021-23337', 'trailing full stop is not part of the link');
  assert.equal(second[2]!.text, '.');
  const para = (doc.content[2] as unknown as { content: { text: string; marks?: { type: string; attrs?: { href: string } }[] }[] }).content;
  assert.equal(para.find((n) => n.marks?.[0]?.type === 'link')!.marks![0]!.attrs!.href, 'https://example.com/a_(b)', 'balanced parentheses stay in the link');
  assert.equal(para.find((n) => n.marks?.[0]?.type === 'code')!.text, 'https://not-a-link.test', 'code spans are not linked');
});

test('integration settings: unknown keys dropped, addresses validated, token required when the host changes', () => {
  const gh = mergeIntegrationConfig('github', undefined, { repo: 'acme/shop', token: 't1', labels: 'a, b', apiBase: 'http://127.0.0.1:9/', evil: 'x', __proto__: { y: 1 } });
  assert.deepEqual(gh, { repo: 'acme/shop', token: 't1', labels: ['a', 'b'], apiBase: 'http://127.0.0.1:9' });
  // blank secret keeps the stored one; same host needs no token
  assert.equal(mergeIntegrationConfig('github', gh, { repo: 'acme/shop', token: '' }).token, 't1');
  assert.equal(mergeIntegrationConfig('github', gh, { apiBase: 'http://127.0.0.1:9/v3' }).token, 't1');
  // moving to another host without the token is refused
  assert.throws(() => mergeIntegrationConfig('github', gh, { apiBase: 'https://evil.example' }), /Enter the token again/);
  assert.throws(() => mergeIntegrationConfig('github', gh, { apiBase: '' }), /Enter the token again/, 'back to api.github.com is a host change too');
  assert.equal(mergeIntegrationConfig('github', gh, { apiBase: 'https://ghe.example/api/v3', token: 't2' }).apiBase, 'https://ghe.example/api/v3');
  // address rules
  for (const bad of ['ftp://x.test', 'http://ghe.example', 'https://user:pw@x.test', 'https://x.test/?a=1', 'https://x.test/#frag', 'not a url', 'javascript:alert(1)']) {
    assert.throws(() => mergeIntegrationConfig('jira', undefined, { baseUrl: bad, email: 'e', apiToken: 't', projectKey: 'P' }), IntegrationError, bad);
  }
  const jira = mergeIntegrationConfig('jira', undefined, { baseUrl: 'https://acme.atlassian.net/', email: 'e', apiToken: 't', projectKey: 'P', issueType: 'Bug', token: 'nope' });
  assert.deepEqual(jira, { baseUrl: 'https://acme.atlassian.net', email: 'e', apiToken: 't', projectKey: 'P', issueType: 'Bug' });
  assert.throws(() => mergeIntegrationConfig('jira', jira, { baseUrl: 'https://other.atlassian.net', apiToken: '' }), /Enter the token again/);
});
